// Token Radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks EVERY pre-token protocol the snapshot's own house rule would
// call rankable — the 40 on the watchlist plus every other pre-token protocol
// that is not a wrapped, staked or bridged product of a token that already
// trades, not a centralised exchange and not a versioned pool — 197 rows here.
// Protocols whose token already trades are kept apart and shown with the
// market's own market cap, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, through a base
// the market itself calibrates:
//
//   fit   log10(market cap) = a + b x log10(TVL), least squares over the live
//         protocols in this snapshot that record both a TVL and a market cap
//         (128 here: a = 3.02, b = 0.52 — the market pays roughly the square
//         root of TVL, so a token's value grows slower than the protocol's size)
//   base  = 10 ^ (a + b x log10(TVL))
//   growth     = clamp(change_7d, -50, 100) per cent; the snapshot's worst
//                outlier (+4,448%) is cut to +100% so one week cannot buy a rank
//   growthMult = 1 + 0.45 x growth / 100
//   maturity   = 0.75 + 0.25 x min(age_days, 1095) / 1095 (age unknown: 365 days)
//   breadth    = 1 + 0.02 x min(chains - 1, 4)  (more chains, wider distribution)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row,
// and the fit's constants come from the snapshot the program is handed, not
// from a number typed in advance.

